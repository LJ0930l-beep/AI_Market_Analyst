function escaped(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function replaceUiPhrase(value: string, source: string, replacement: string): string {
  if (/^[A-Za-z0-9_]+$/.test(source)) {
    return value.replace(new RegExp(`(?<![A-Za-z0-9_])${escaped(source)}(?![A-Za-z0-9_])`, "g"), replacement);
  }
  return value.replaceAll(source, replacement);
}

function readStoredLanguage(): Language | undefined {
  if (typeof window === "undefined") return undefined;
  try {
    const stored = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    return stored === "en" || stored === "zh-CN" ? stored : undefined;
  } catch {
    return undefined;
  }
}

export function detectBrowserLanguage(): Language {
  if (typeof navigator === "undefined") return "en";
  const candidates = [...(navigator.languages ?? []), navigator.language];
  return candidates.some((value) => value?.toLowerCase().startsWith("zh")) ? "zh-CN" : "en";
}

export function resolveInitialLanguage(): Language {
  return readStoredLanguage() ?? detectBrowserLanguage();
}

export function translateText(value: string, language: Language): string {
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const trimmed = value.trim();
  if (!trimmed) return value;
  if (trimmed.startsWith("{") || trimmed.startsWith("[")) return value;
  if (language === "zh-CN") {
    const key = englishByText.get(trimmed) ?? enumText[trimmed];
    if (key) return `${leading}${zhCN[key]}${trailing}`;
    let translated = trimmed;
    for (const [source, sourceKey] of [...englishByText.entries()].sort((left, right) => right[0].length - left[0].length)) {
      if (source.length > 2 && translated.includes(source)) translated = replaceUiPhrase(translated, source, zhCN[sourceKey]);
    }
    for (const [source, sourceKey] of Object.entries(enumText)) {
      translated = translated.replace(new RegExp(`(?<![A-Za-z_])${source}(?![A-Za-z_])`, "g"), zhCN[sourceKey]);
    }
    return `${leading}${translated}${trailing}`;
  }
  const key = chineseByText.get(trimmed) ?? enumTextChinese[trimmed];
  if (key) return `${leading}${en[key]}${trailing}`;
  let translated = trimmed;
  for (const [source, sourceKey] of [...chineseByText.entries()].sort((left, right) => right[0].length - left[0].length)) {
    if (source.length > 1 && translated.includes(source)) translated = replaceUiPhrase(translated, source, en[sourceKey]);
  }
  for (const [source, sourceKey] of Object.entries(enumTextChinese)) {
    translated = translated.replaceAll(source, en[sourceKey]);
  }
  return `${leading}${translated}${trailing}`;
}

export function translateKey(key: TranslationKey, language: Language): string {
  return language === "zh-CN" ? zhCN[key] : en[key];
}

interface I18nContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: TranslationKey) => string;
  text: (value: string) => string;
  formatNumber: (value: number, options?: Intl.NumberFormatOptions) => string;
  formatDateTime: (value: string | Date, options?: Intl.DateTimeFormatOptions) => string;
  formatPercent: (value: number) => string;
}

const defaultContext: I18nContextValue = {
  language: "en",
  setLanguage: () => undefined,
  t: (key) => en[key],
  text: (value) => value,
  formatNumber: (value, options) => new Intl.NumberFormat("en", options).format(value),
  formatDateTime: (value, options) => new Intl.DateTimeFormat("en", options).format(new Date(value)),
  formatPercent: (value) => new Intl.NumberFormat("en", { style: "percent", maximumFractionDigits: 1 }).format(value),
};

const I18nContext = createContext<I18nContextValue>(defaultContext);

export function useI18n(): I18nContextValue {
  return useContext(I18nContext);
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(resolveInitialLanguage);
  const setLanguage = (next: Language) => {
    setLanguageState(next);
    try {
      window.localStorage.setItem(LANGUAGE_STORAGE_KEY, next);
    } catch {
      // Local persistence is best effort; the current session remains usable.
    }
  };
  const value = useMemo<I18nContextValue>(() => ({
    language,
    setLanguage,
    t: (key) => translateKey(key, language),
    text: (text) => translateText(text, language),
    formatNumber: (number, options) => new Intl.NumberFormat(language, options).format(number),
    formatDateTime: (date, options) => new Intl.DateTimeFormat(language, {
      dateStyle: "medium",
      timeStyle: "short",
      ...options,
    }).format(new Date(date)),
    formatPercent: (number) => new Intl.NumberFormat(language, { style: "percent", maximumFractionDigits: 1 }).format(number),
  }), [language]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

function localizeNode(node: ReactNode, language: Language): ReactNode {
  if (typeof node === "string") return translateText(node, language);
  if (Array.isArray(node)) return node.map((child) => localizeNode(child, language));
  if (!isValidElement(node)) return node;
  const element = node as ReactElement<{ children?: ReactNode; [key: string]: unknown }>;
  const props = { ...element.props };
  const originalChildren = props.children;
  delete props.children;
  for (const attribute of ["aria-label", "placeholder", "title", "alt"]) {
    if (typeof props[attribute] === "string") props[attribute] = translateText(props[attribute], language);
  }
  for (const property of ["title", "freshness", "emptyMessage", "degradedMessage"]) {
    if (typeof props[property] === "string") props[property] = translateText(props[property], language);
  }
  if (typeof originalChildren === "undefined") return cloneElement(element, props);
  const localizedChildren = localizeNode(originalChildren, language);
  return Array.isArray(localizedChildren)
    ? cloneElement(element, props, ...localizedChildren)
    : cloneElement(element, props, localizedChildren);
}

export function LocalizedSurface({ children }: { children: ReactNode }) {
  const { language } = useI18n();
  return <>{localizeNode(children, language)}</>;
}

